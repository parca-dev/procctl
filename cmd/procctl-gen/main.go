// procctl-gen generates matching C and Go code for a consumer's payload and
// state schemas (plan §5.5), plus golden vectors that both sides are tested
// against.
//
//	procctl-gen -schema testproto.procctl.json -c-out DIR -go-out DIR -go-package NAME -vectors DIR
//
// Schema (JSON):
//
//	{
//	  "consumer": "testproto", "schema_version": 1,
//	  "kinds": {"token": 1},
//	  "messages": {
//	    "agent":  [{"name": "seq_tag", "type": "u64"}, {"name": "pattern", "type": "u8", "count": 32}],
//	    "status": [...]
//	  }
//	}
//
// Types: u8 u16 u32 u64 i8 i16 i32 i64 f32 f64, optionally with "count" for a
// fixed array. Fields are naturally aligned; padding is explicit in the C
// struct, and every offset is checked with _Static_assert. Encoding is
// little-endian. Message sizes are rounded up to 8 bytes.
package main

import (
	"bytes"
	"encoding/binary"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type field struct {
	Name  string `json:"name"`
	Type  string `json:"type"`
	Count int    `json:"count"`
}

type schema struct {
	Consumer      string             `json:"consumer"`
	SchemaVersion uint32             `json:"schema_version"`
	Kinds         map[string]uint32  `json:"kinds"`
	Messages      map[string][]field `json:"messages"`
}

type ftype struct {
	size     int
	c, g     string
	unsigned bool
	float    bool
}

var types = map[string]ftype{
	"u8": {1, "uint8_t", "uint8", true, false}, "u16": {2, "uint16_t", "uint16", true, false},
	"u32": {4, "uint32_t", "uint32", true, false}, "u64": {8, "uint64_t", "uint64", true, false},
	"i8": {1, "int8_t", "int8", false, false}, "i16": {2, "int16_t", "int16", false, false},
	"i32": {4, "int32_t", "int32", false, false}, "i64": {8, "int64_t", "int64", false, false},
	"f32": {4, "float", "float32", false, true}, "f64": {8, "double", "float64", false, true},
}

var ident = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

type laid struct {
	field
	t      ftype
	offset int
	n      int // elements (1 for scalars)
}

type message struct {
	name   string
	fields []laid
	size   int
}

func layout(name string, fs []field) (message, error) {
	m := message{name: name}
	off := 0
	seen := map[string]bool{}
	for _, f := range fs {
		t, ok := types[f.Type]
		if !ok {
			return m, fmt.Errorf("%s.%s: unknown type %q", name, f.Name, f.Type)
		}
		if !ident.MatchString(f.Name) || seen[f.Name] {
			return m, fmt.Errorf("%s: bad or duplicate field name %q", name, f.Name)
		}
		seen[f.Name] = true
		n := f.Count
		if n == 0 {
			n = 1
		}
		off = (off + t.size - 1) / t.size * t.size
		m.fields = append(m.fields, laid{field: f, t: t, offset: off, n: n})
		off += t.size * n
	}
	m.size = (off + 7) &^ 7
	return m, nil
}

func camel(s string) string {
	var b strings.Builder
	for _, p := range strings.Split(s, "_") {
		if p != "" {
			b.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return b.String()
}

// sample gives every element a deterministic, type-dependent value.
func sample(f laid, i int) any {
	k := uint64(f.offset + i + 1)
	switch f.Type {
	case "f32":
		return float32(k) + 0.5
	case "f64":
		return float64(k) + 0.25
	}
	v := k * 0x0101010101010101 >> (64 - 8*uint(f.t.size))
	if !f.t.unsigned {
		v |= 1 << (8*uint(f.t.size) - 1) // exercise the sign bit
	}
	return v
}

func encodeSample(m message) []byte {
	b := make([]byte, m.size)
	for _, f := range m.fields {
		for i := 0; i < f.n; i++ {
			at := b[f.offset+i*f.t.size:]
			switch v := sample(f, i).(type) {
			case float32:
				binary.LittleEndian.PutUint32(at, math.Float32bits(v))
			case float64:
				binary.LittleEndian.PutUint64(at, math.Float64bits(v))
			case uint64:
				switch f.t.size {
				case 1:
					at[0] = byte(v)
				case 2:
					binary.LittleEndian.PutUint16(at, uint16(v))
				case 4:
					binary.LittleEndian.PutUint32(at, uint32(v))
				case 8:
					binary.LittleEndian.PutUint64(at, v)
				}
			}
		}
	}
	return b
}

func cLiteral(f laid, i int) string {
	switch v := sample(f, i).(type) {
	case float32:
		return fmt.Sprintf("%gf", v)
	case float64:
		return fmt.Sprintf("%g", v)
	case uint64:
		if f.t.unsigned {
			return fmt.Sprintf("UINT64_C(%d)", v)
		}
		return fmt.Sprintf("(%s)UINT64_C(%d)", f.t.c, v)
	}
	return "0"
}

func genC(s schema, msgs []message) []byte {
	var b bytes.Buffer
	P := strings.ToUpper(s.Consumer)
	fmt.Fprintf(&b, "/* Code generated by procctl-gen. DO NOT EDIT. */\n")
	fmt.Fprintf(&b, "#ifndef %s_SCHEMA_H\n#define %s_SCHEMA_H\n\n", P, P)
	fmt.Fprintf(&b, "#include <stddef.h>\n#include <stdint.h>\n#include <string.h>\n\n")
	fmt.Fprintf(&b, "#define %s_CONSUMER \"%s\"\n#define %s_SCHEMA_VERSION %du\n", P, s.Consumer, P, s.SchemaVersion)
	var ks []string
	for k := range s.Kinds {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	for _, k := range ks {
		fmt.Fprintf(&b, "#define %s_KIND_%s %du\n", P, strings.ToUpper(k), s.Kinds[k])
	}
	fmt.Fprintf(&b, "\n#ifdef __cplusplus\n#define %s__SA static_assert\n#else\n#define %s__SA _Static_assert\n#endif\n", P, P)
	for _, m := range msgs {
		tn := fmt.Sprintf("%s_%s_t", s.Consumer, m.name)
		fmt.Fprintf(&b, "\n/* %s.%s: %d bytes, little-endian. */\ntypedef struct %s_%s {\n", s.Consumer, m.name, m.size, s.Consumer, m.name)
		off, pad := 0, 0
		for _, f := range m.fields {
			if f.offset > off {
				fmt.Fprintf(&b, "  uint8_t _pad%d[%d];\n", pad, f.offset-off)
				pad++
			}
			if f.Count > 0 {
				fmt.Fprintf(&b, "  %s %s[%d];\n", f.t.c, f.Name, f.Count)
			} else {
				fmt.Fprintf(&b, "  %s %s;\n", f.t.c, f.Name)
			}
			off = f.offset + f.t.size*f.n
		}
		if m.size > off {
			fmt.Fprintf(&b, "  uint8_t _pad%d[%d];\n", pad, m.size-off)
		}
		fmt.Fprintf(&b, "} %s;\n", tn)
		fmt.Fprintf(&b, "%s__SA(sizeof(%s) == %d, \"%s size\");\n", P, tn, m.size, tn)
		for _, f := range m.fields {
			fmt.Fprintf(&b, "%s__SA(offsetof(%s, %s) == %d, \"%s.%s offset\");\n", P, tn, f.Name, f.offset, tn, f.Name)
		}
		fmt.Fprintf(&b, "\n/* The deterministic sample encoded in testdata (golden vector). */\n")
		fmt.Fprintf(&b, "static inline void %s_%s_sample(%s *m) {\n  memset(m, 0, sizeof *m);\n", s.Consumer, m.name, tn)
		for _, f := range m.fields {
			for i := 0; i < f.n; i++ {
				if f.Count > 0 {
					fmt.Fprintf(&b, "  m->%s[%d] = %s;\n", f.Name, i, cLiteral(f, i))
				} else {
					fmt.Fprintf(&b, "  m->%s = %s;\n", f.Name, cLiteral(f, i))
				}
			}
		}
		fmt.Fprintf(&b, "}\n")
	}
	fmt.Fprintf(&b, "\n#endif\n")
	return b.Bytes()
}

func genGo(s schema, msgs []message, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by procctl-gen. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	fmt.Fprintf(&b, "import (\n\"encoding/binary\"\n\"errors\"\n\"math\"\n)\n\nvar _ = math.Float32bits\n\n")
	fmt.Fprintf(&b, "const (\nConsumer = %q\nSchemaVersion = %d\n", s.Consumer, s.SchemaVersion)
	var ks []string
	for k := range s.Kinds {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	for _, k := range ks {
		fmt.Fprintf(&b, "Kind%s = %d\n", camel(k), s.Kinds[k])
	}
	fmt.Fprintf(&b, ")\n\nvar errShort = errors.New(%q)\n", s.Consumer+": short buffer")
	for _, m := range msgs {
		tn := camel(m.name)
		fmt.Fprintf(&b, "\n// %s is %s.%s (%d bytes, little-endian).\ntype %s struct {\n", tn, s.Consumer, m.name, m.size, tn)
		for _, f := range m.fields {
			if f.Count > 0 {
				fmt.Fprintf(&b, "%s [%d]%s\n", camel(f.Name), f.Count, f.t.g)
			} else {
				fmt.Fprintf(&b, "%s %s\n", camel(f.Name), f.t.g)
			}
		}
		fmt.Fprintf(&b, "}\n\n// %sSize is the encoded size of %s.\nconst %sSize = %d\n\n", tn, tn, tn, m.size)

		enc := func(f laid, expr, at string) string {
			switch f.Type {
			case "u8":
				return fmt.Sprintf("b[%s] = %s\n", at, expr)
			case "i8":
				return fmt.Sprintf("b[%s] = byte(%s)\n", at, expr)
			case "f32":
				return fmt.Sprintf("binary.LittleEndian.PutUint32(b[%s:], math.Float32bits(%s))\n", at, expr)
			case "f64":
				return fmt.Sprintf("binary.LittleEndian.PutUint64(b[%s:], math.Float64bits(%s))\n", at, expr)
			}
			bits := 8 * f.t.size
			return fmt.Sprintf("binary.LittleEndian.PutUint%d(b[%s:], uint%d(%s))\n", bits, at, bits, expr)
		}
		dec := func(f laid, dst, at string) string {
			switch f.Type {
			case "u8":
				return fmt.Sprintf("%s = b[%s]\n", dst, at)
			case "i8":
				return fmt.Sprintf("%s = int8(b[%s])\n", dst, at)
			case "f32":
				return fmt.Sprintf("%s = math.Float32frombits(binary.LittleEndian.Uint32(b[%s:]))\n", dst, at)
			case "f64":
				return fmt.Sprintf("%s = math.Float64frombits(binary.LittleEndian.Uint64(b[%s:]))\n", dst, at)
			}
			return fmt.Sprintf("%s = %s(binary.LittleEndian.Uint%d(b[%s:]))\n", dst, f.t.g, 8*f.t.size, at)
		}
		fmt.Fprintf(&b, "// MarshalBinary encodes m.\nfunc (m *%s) MarshalBinary() ([]byte, error) {\nb := make([]byte, %sSize)\n", tn, tn)
		for _, f := range m.fields {
			if f.Count > 0 {
				fmt.Fprintf(&b, "for i := range m.%s {\n%s}\n", camel(f.Name),
					enc(f, fmt.Sprintf("m.%s[i]", camel(f.Name)), fmt.Sprintf("%d+i*%d", f.offset, f.t.size)))
			} else {
				b.WriteString(enc(f, "m."+camel(f.Name), fmt.Sprint(f.offset)))
			}
		}
		fmt.Fprintf(&b, "return b, nil\n}\n\n")
		fmt.Fprintf(&b, "// UnmarshalBinary decodes m from b (len(b) >= %sSize).\nfunc (m *%s) UnmarshalBinary(b []byte) error {\nif len(b) < %sSize {\nreturn errShort\n}\n", tn, tn, tn)
		for _, f := range m.fields {
			if f.Count > 0 {
				fmt.Fprintf(&b, "for i := range m.%s {\n%s}\n", camel(f.Name),
					dec(f, fmt.Sprintf("m.%s[i]", camel(f.Name)), fmt.Sprintf("%d+i*%d", f.offset, f.t.size)))
			} else {
				b.WriteString(dec(f, "m."+camel(f.Name), fmt.Sprint(f.offset)))
			}
		}
		fmt.Fprintf(&b, "return nil\n}\n\n")
		fmt.Fprintf(&b, "// Sample%s returns the deterministic sample encoded in the golden vector.\nfunc Sample%s() %s {\nvar m %s\n", tn, tn, tn, tn)
		for _, f := range m.fields {
			for i := 0; i < f.n; i++ {
				lhs := "m." + camel(f.Name)
				if f.Count > 0 {
					lhs = fmt.Sprintf("%s[%d]", lhs, i)
				}
				switch v := sample(f, i).(type) {
				case float32, float64:
					fmt.Fprintf(&b, "%s = %v\n", lhs, v)
				case uint64:
					if f.t.unsigned {
						fmt.Fprintf(&b, "%s = %d\n", lhs, v)
					} else {
						shift := uint(64 - 8*f.t.size)
						fmt.Fprintf(&b, "%s = %d\n", lhs, int64(v<<shift)>>shift)
					}
				}
			}
		}
		fmt.Fprintf(&b, "return m\n}\n")
	}
	return format.Source(b.Bytes())
}

func main() {
	schemaPath := flag.String("schema", "", "schema JSON file")
	cOut := flag.String("c-out", "", "directory for <consumer>_schema.h")
	goOut := flag.String("go-out", "", "directory for schema_gen.go")
	goPkg := flag.String("go-package", "", "Go package name (default: consumer)")
	vecOut := flag.String("vectors", "", "directory for <consumer>_<message>.bin golden vectors")
	flag.Parse()
	if err := run(*schemaPath, *cOut, *goOut, *goPkg, *vecOut); err != nil {
		fmt.Fprintln(os.Stderr, "procctl-gen:", err)
		os.Exit(1)
	}
}

func run(schemaPath, cOut, goOut, goPkg, vecOut string) error {
	raw, err := os.ReadFile(schemaPath)
	if err != nil {
		return err
	}
	var s schema
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&s); err != nil {
		return err
	}
	if !ident.MatchString(s.Consumer) || len(s.Consumer) > 31 {
		return fmt.Errorf("bad consumer name %q", s.Consumer)
	}
	var names []string
	for n := range s.Messages {
		if !ident.MatchString(n) {
			return fmt.Errorf("bad message name %q", n)
		}
		names = append(names, n)
	}
	sort.Strings(names)
	var msgs []message
	for _, n := range names {
		m, err := layout(n, s.Messages[n])
		if err != nil {
			return err
		}
		msgs = append(msgs, m)
	}
	if goPkg == "" {
		goPkg = s.Consumer
	}
	if cOut != "" {
		if err := os.WriteFile(filepath.Join(cOut, s.Consumer+"_schema.h"), genC(s, msgs), 0o644); err != nil {
			return err
		}
	}
	if goOut != "" {
		src, err := genGo(s, msgs, goPkg)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(goOut, "schema_gen.go"), src, 0o644); err != nil {
			return err
		}
	}
	if vecOut != "" {
		for _, m := range msgs {
			p := filepath.Join(vecOut, fmt.Sprintf("%s_%s.bin", s.Consumer, m.name))
			if err := os.WriteFile(p, encodeSample(m), 0o644); err != nil {
				return err
			}
		}
	}
	return nil
}
